-- Subscription analytics: raw tables written by the proxy collector.
-- Apply as the schema owner (admin), not as the collector role.
-- This is the first-install schema (version 1). Re-running it on a version-1
-- database is safe (IF NOT EXISTS). It is not a migration tool: a later version
-- ships its own ALTER script.

CREATE SCHEMA IF NOT EXISTS subscription_analytics;

-- One row per upstream attempt (one usage.Record). No bodies, messages, keys,
-- emails, auth IDs, base URLs or free-form headers.
CREATE TABLE IF NOT EXISTS subscription_analytics.attempts (
    event_id                     uuid PRIMARY KEY,          -- generated by the collector; replay key
    collector_run_id             uuid NOT NULL,
    received_at                  timestamptz NOT NULL,      -- when the collector got the record
    trace_id                     text,                      -- inbound request UUIDv7 (shared by retries)
    attempt_id                   text,                      -- per-attempt UUID from the usage reporter
    provider                     text NOT NULL,
    executor_type                text,
    auth_kind                    text,                      -- 'oauth' = subscription, 'apikey' = paid API, NULL = unknown
    account_hash                 text,                      -- sha256 hex of the auth ID (domain separated)
    client_key_hash              text,                      -- sha256 hex of the client API key
    requested_model              text,
    upstream_model               text,
    served_model                 text,                      -- model the upstream reported; NULL when unknown
    requested_effort             text,
    upstream_effort              text,
    requested_tier               text,
    served_tier                  text,
    stream                       boolean NOT NULL,
    started_at                   timestamptz,
    ended_at                     timestamptz,
    latency_ms                   bigint,
    ttft_ms                      bigint,                    -- NULL when not measured
    failed                       boolean NOT NULL,
    origin                       text NOT NULL,             -- evidence, see README: 'upstream_response' | 'upstream_no_response' | 'unmarked'
    http_status                  integer,
    error_type                   text,                      -- sanitized error.type / type
    error_code                   text,                      -- sanitized error.code / error.status
    failure_class                text,                      -- existing auth classifier verdict
    classifier_version           smallint,
    usage_known                  boolean NOT NULL,          -- false: all token columns are NULL
    raw_input_tokens             bigint,
    raw_output_tokens            bigint,
    raw_reasoning_tokens         bigint,
    raw_cached_tokens            bigint,
    raw_cache_read_tokens        bigint,
    raw_cache_creation_tokens    bigint,
    raw_cache_creation_5m_tokens bigint,                    -- NULL when the TTL split is unknown
    raw_cache_creation_1h_tokens bigint,
    raw_total_tokens             bigint,
    accounting_version           smallint,
    accounting_quality           text,                      -- complete | unclassified | inconsistent
    total_tokens                 bigint,                    -- normalized, non-overlapping buckets below
    input_uncached_tokens        bigint,
    input_cache_read_tokens      bigint,
    input_cache_write_tokens     bigint,
    output_non_reasoning_tokens  bigint,
    output_reasoning_tokens      bigint,
    unclassified_tokens          bigint,
    CHECK (origin IN ('upstream_response', 'upstream_no_response', 'unmarked')),
    CHECK (accounting_quality IS NULL OR accounting_quality IN ('complete', 'unclassified', 'inconsistent')),
    CHECK (latency_ms IS NULL OR latency_ms >= 0),
    CHECK (ttft_ms IS NULL OR ttft_ms >= 0),
    CHECK (ended_at IS NULL OR started_at IS NULL OR ended_at >= started_at),
    CHECK (usage_known OR num_nonnulls(raw_input_tokens, raw_output_tokens, raw_reasoning_tokens, raw_cached_tokens,
        raw_cache_read_tokens, raw_cache_creation_tokens, raw_cache_creation_5m_tokens, raw_cache_creation_1h_tokens,
        raw_total_tokens, total_tokens, input_uncached_tokens, input_cache_read_tokens, input_cache_write_tokens,
        output_non_reasoning_tokens, output_reasoning_tokens, unclassified_tokens) = 0),
    CHECK (LEAST(raw_input_tokens, raw_output_tokens, raw_reasoning_tokens, raw_cached_tokens, raw_cache_read_tokens,
        raw_cache_creation_tokens, raw_cache_creation_5m_tokens, raw_cache_creation_1h_tokens, raw_total_tokens,
        total_tokens, input_uncached_tokens, input_cache_read_tokens, input_cache_write_tokens,
        output_non_reasoning_tokens, output_reasoning_tokens, unclassified_tokens) >= 0
        OR num_nonnulls(raw_input_tokens, raw_output_tokens, raw_reasoning_tokens, raw_cached_tokens,
        raw_cache_read_tokens, raw_cache_creation_tokens, raw_cache_creation_5m_tokens, raw_cache_creation_1h_tokens,
        raw_total_tokens, total_tokens, input_uncached_tokens, input_cache_read_tokens, input_cache_write_tokens,
        output_non_reasoning_tokens, output_reasoning_tokens, unclassified_tokens) = 0)
);
CREATE INDEX IF NOT EXISTS attempts_account_ended_idx ON subscription_analytics.attempts (account_hash, ended_at);
CREATE INDEX IF NOT EXISTS attempts_ended_idx ON subscription_analytics.attempts (ended_at);
CREATE INDEX IF NOT EXISTS attempts_no_end_idx
    ON subscription_analytics.attempts (account_hash, received_at) WHERE ended_at IS NULL;
CREATE INDEX IF NOT EXISTS attempts_no_account_idx
    ON subscription_analytics.attempts (provider, ended_at) WHERE account_hash IS NULL;

-- One row per reported usage percentage of one quota window.
CREATE TABLE IF NOT EXISTS subscription_analytics.quota_observations (
    observation_id      uuid PRIMARY KEY,
    collector_run_id    uuid NOT NULL,
    received_at         timestamptz NOT NULL,
    source              text NOT NULL,          -- 'response_header' | 'usage_poll'
    attempt_event_id    uuid,                   -- attempts.event_id for response_header rows
    observed_at         timestamptz NOT NULL,   -- see observed_at_quality
    observed_at_quality text NOT NULL,          -- 'header_received': proxy got the headers at this time
                                                -- 'attempt_end': receive time unknown, this is an upper bound
                                                -- 'poll': time of the usage poll response
    observed_not_before timestamptz,            -- header rows: attempt start (lower bound)
    provider            text NOT NULL,
    auth_kind           text,
    account_hash        text NOT NULL,
    window_key          text NOT NULL,          -- 'short' | 'weekly' | 'fable_weekly'
    raw_window          text NOT NULL,          -- e.g. '5h', '7d', 'primary', 'secondary', 'poll'
    window_minutes      integer,                -- when reported
    used_percent        double precision NOT NULL, -- normalized 0..100
    raw_value           text NOT NULL,          -- value as reported (header) or as parsed (poll)
    raw_scale           text NOT NULL,          -- 'fraction' (0..1) | 'percent' (0..100)
    raw_decimals        smallint,               -- digits after the point in raw_value; NULL for polls
    reset_at            timestamptz,            -- reported reset; NULL when missing
    reset_kind          text,                   -- 'absolute' | 'relative' | NULL
    status              text,                   -- e.g. 'allowed', 'rejected' when reported
    CHECK (source IN ('response_header', 'usage_poll')),
    CHECK (observed_at_quality IN ('header_received', 'attempt_end', 'poll')),
    CHECK (window_key IN ('short', 'weekly', 'fable_weekly')),
    CHECK (raw_scale IN ('fraction', 'percent')),
    CHECK (reset_kind IS NULL OR reset_kind IN ('absolute', 'relative')),
    -- Finite and plausible; values above 100 can be real (overage) and are kept.
    CHECK (used_percent >= 0 AND used_percent <= 1000),
    CHECK (window_minutes IS NULL OR window_minutes > 0),
    CHECK (raw_decimals IS NULL OR raw_decimals >= 0)
);
CREATE INDEX IF NOT EXISTS quota_observations_key_idx
    ON subscription_analytics.quota_observations (account_hash, window_key, observed_at);

-- Collector run markers and counters. Rows go through the same batch/spool path
-- as data, so a database outage does not look like a collection gap.
CREATE TABLE IF NOT EXISTS subscription_analytics.collector_heartbeats (
    run_id             uuid NOT NULL,
    seq                bigint NOT NULL,
    at                 timestamptz NOT NULL,
    kind               text NOT NULL,           -- 'start' | 'beat' | 'stop'
    queue_dropped      bigint NOT NULL,         -- rows lost because the queue was full (cumulative per run)
    spool_dropped      bigint NOT NULL,         -- rows lost because the spool was full or failed
    spooled            bigint NOT NULL,         -- rows written to the spool
    spool_bytes        bigint NOT NULL,         -- spool size at this time
    write_errors       bigint NOT NULL,         -- failed database writes
    PRIMARY KEY (run_id, seq),
    CHECK (kind IN ('start', 'beat', 'stop')),
    CHECK (LEAST(seq, queue_dropped, spool_dropped, spooled, spool_bytes, write_errors) >= 0)
);
CREATE INDEX IF NOT EXISTS collector_heartbeats_at_idx ON subscription_analytics.collector_heartbeats (at);
